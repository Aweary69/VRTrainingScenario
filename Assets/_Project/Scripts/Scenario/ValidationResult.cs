namespace Project.Scenario
{
    /// <summary>
    /// Результат сравнения входящего действия игрока с ожиданиями текущей группы.
    /// Финальная таблица решений (см. README):
    ///
    /// | Событие                                                    | Результат       |
    /// |-------------------------------------------------------------|-----------------|
    /// | Не найдено ни в шагах, ни в дистракторах текущей группы     | Ignore          |
    /// | Совпадает с текущим ожидаемым действием                     | Success         |
    /// | Дистрактор группы, либо другое действие текущего шага        | Mismatch        |
    /// | Относится к действию будущего шага той же группы            | SequenceBroken  |
    /// </summary>
    public enum ValidationResult
    {
        Ignore,
        Success,
        Mismatch,
        SequenceBroken
    }
}
